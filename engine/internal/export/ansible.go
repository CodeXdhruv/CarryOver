package export

import (
	"fmt"
	"strings"

	"github.com/carryover/carryover/engine/internal/manifest"
)

// GenerateAnsiblePlaybook creates an idempotent Ansible playbook from a migration manifest
func GenerateAnsiblePlaybook(m *manifest.Manifest, targetPM string) (string, error) {
	if m == nil {
		return "", fmt.Errorf("manifest cannot be nil")
	}

	var sb strings.Builder
	sb.WriteString("---\n")
	sb.WriteString("# Generated by Carryover - Linux OS Migration\n")
	sb.WriteString(fmt.Sprintf("# Source OS: %s %s\n", m.BackupMeta.Source.OSID, m.BackupMeta.Source.OSVersion))
	sb.WriteString(fmt.Sprintf("# Created: %s\n", m.BackupMeta.Created))
	sb.WriteString("- name: Carryover System Migration Provisioning\n")
	sb.WriteString("  hosts: localhost\n")
	sb.WriteString("  connection: local\n")
	sb.WriteString("  become: false\n")
	sb.WriteString("  tasks:\n")

	// 1. Native package installation tasks
	if targetPM == "" {
		targetPM = m.BackupMeta.Source.PackageManager
	}

	var nativePkgs []string
	switch targetPM {
	case "apt":
		for _, a := range m.Apps.Apt {
			nativePkgs = append(nativePkgs, a.Name)
		}
	case "dnf":
		for _, a := range m.Apps.Dnf {
			nativePkgs = append(nativePkgs, a.Name)
		}
	case "pacman":
		for _, a := range m.Apps.Pacman {
			nativePkgs = append(nativePkgs, a.Name)
		}
	case "zypper":
		for _, a := range m.Apps.Zypper {
			nativePkgs = append(nativePkgs, a.Name)
		}
	}

	if len(nativePkgs) > 0 {
		sb.WriteString(fmt.Sprintf("\n    - name: Install system packages via %s\n", targetPM))
		sb.WriteString("      become: true\n")
		switch targetPM {
		case "apt":
			sb.WriteString("      ansible.builtin.apt:\n")
			sb.WriteString("        pkg:\n")
			for _, p := range nativePkgs {
				sb.WriteString(fmt.Sprintf("          - %s\n", p))
			}
			sb.WriteString("        state: present\n")
			sb.WriteString("        update_cache: true\n")
		case "dnf":
			sb.WriteString("      ansible.builtin.dnf:\n")
			sb.WriteString("        name:\n")
			for _, p := range nativePkgs {
				sb.WriteString(fmt.Sprintf("          - %s\n", p))
			}
			sb.WriteString("        state: present\n")
		case "pacman":
			sb.WriteString("      community.general.pacman:\n")
			sb.WriteString("        name:\n")
			for _, p := range nativePkgs {
				sb.WriteString(fmt.Sprintf("          - %s\n", p))
			}
			sb.WriteString("        state: present\n")
		case "zypper":
			sb.WriteString("      community.general.zypper:\n")
			sb.WriteString("        name:\n")
			for _, p := range nativePkgs {
				sb.WriteString(fmt.Sprintf("          - %s\n", p))
			}
			sb.WriteString("        state: present\n")
		}
	}

	// 2. Flatpak applications
	if len(m.Apps.Flatpak) > 0 {
		sb.WriteString("\n    - name: Install Flatpak applications\n")
		sb.WriteString("      community.general.flatpak:\n")
		sb.WriteString("        name:\n")
		for _, f := range m.Apps.Flatpak {
			sb.WriteString(fmt.Sprintf("          - %s\n", f.ID))
		}
		sb.WriteString("        state: present\n")
		sb.WriteString("        method: user\n")
	}

	// 3. Rebuild directories
	if len(m.Projects) > 0 {
		sb.WriteString("\n    - name: Rebuild developer projects\n")
		for _, prj := range m.Projects {
			if len(prj.Rebuild) > 0 {
				sb.WriteString(fmt.Sprintf("    - name: Rebuild %s\n", prj.Path))
				sb.WriteString("      ansible.builtin.command:\n")
				sb.WriteString(fmt.Sprintf("        cmd: %s\n", prj.Rebuild[0]))
				sb.WriteString(fmt.Sprintf("        chdir: \"{{ ansible_env.HOME }}/%s\"\n", prj.Path))
			}
		}
	}

	return sb.String(), nil
}
